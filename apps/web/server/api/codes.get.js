import{currentUser}from"../utils/auth";
import{codes,earlyCount,findPlayer,rankBanned}from"../utils/players";
import{entitlementFor}from"../utils/entitlements";
import{tierForElo}from"@ranked-world/ranks";
import voice from"../../../../packages/shared/voice.cjs";
import membershipConfig from"../../../../packages/shared/membership.cjs";
import{POLICY_VERSION}from"../../app/utils/legal.js";
export default defineEventHandler(async event=>{
const user=currentUser(event);
if(!user)return{codes:[],bracket:null,reason:"signed-out"};
const doc=await findPlayer(user.id);
if(!doc||!doc.linked)return{codes:[],bracket:null,reason:"unlinked"};
if(doc.acceptance?.account?.version!==POLICY_VERSION)return{codes:[],bracket:null,reason:"policy"};
if(await rankBanned(doc))return{codes:[],bracket:null,reason:"banned"};
if(!doc.modMode&&doc.modHold?.at)return{codes:[],bracket:null,reason:"mods",mods:doc.modHold.mods||[]};
if(!doc.modMode&&!voice.voiceAccepted(doc))return{codes:[],bracket:null,reason:"voice-consent",version:voice.VOICE_VERSION};
if(doc.modMode)return{codes:await codes(null,true),bracket:"All (moderation mode)",reason:null};
const elo=doc.ranked?.elo||0;
const bracket=tierForElo(elo).category;
const order=["LOW","MID","HIGH","TOP"],lines=[600,900,1200],i=order.indexOf(bracket);
const extra=[];
if(i>0&&elo-lines[i-1]<100)extra.push(order[i-1]);
if(i>=0&&i<order.length-1&&lines[i]-elo<=100)extra.push(order[i+1]);
const perks=await entitlementFor(user.id);
const t=doc.tries||{};
const pass=!perks.firstIn&&membershipConfig.tryLive(t.firstInAt,membershipConfig.FIRST_IN_MS);
const peek=!perks.lobbyPreview&&membershipConfig.tryLive(t.peekAt,membershipConfig.PEEK_MS);
const view={...perks,firstIn:perks.firstIn||pass,peekCode:peek?t.peekCode:null};
const list=(await Promise.all([bracket,...extra].map(c=>codes(c,false,view)))).flat();
const hidden=view.firstIn?0:await earlyCount([bracket,...extra]);
const tries={peek:!perks.lobbyPreview&&membershipConfig.tryReady(t.peekAt),firstIn:!perks.firstIn&&membershipConfig.tryReady(t.firstInAt),pass,peekCode:view.peekCode};
return{codes:list,bracket:extra.length?[bracket,...extra].join(" + "):bracket,reason:null,hidden,firstIn:Boolean(perks.firstIn),lobbyPreview:Boolean(perks.lobbyPreview),tries};
});
